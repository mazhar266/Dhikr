fun main() {
    val store = FileDhikrStore(
        File(System.getProperty("user.home"), ".dhikr").resolve("dhikr_state.txt"),
    )
    val repo = DhikrRepository(store, SystemClock())
    repo.load()
    val model = AppModel(repo)

    // Window/taskbar icon; generated by tools/gen_icons.py.
    val icon = Thread.currentThread().contextClassLoader.getResourceAsStream("icon.png")
        ?.use { BitmapPainter(ImageIO.read(it).toComposeImageBitmap()) }

    application {
        Window(
            onCloseRequest = ::exitApplication,
            title = "Dhikr",
            icon = icon,
            state = rememberWindowState(size = DpSize(430.dp, 820.dp)),
            onPreviewKeyEvent = { handleReaderCountKey(model, it) },
        ) {
            CompositionLocalProvider(LocalAppPlatform provides DesktopPlatform) {
                DhikrApp(model)
            }
        }
    }
}

private fun handleReaderCountKey(model: AppModel, event: KeyEvent): Boolean {
    val reader = model.screen as? Screen.Reader ?: return false
    if (event.isAltPressed || event.isCtrlPressed || event.isMetaPressed || event.isShiftPressed) return false
    when (event.key) {
        Key.Spacebar, Key.Enter, Key.NumPadEnter, Key.DirectionRight -> Unit
        else -> return false
    }
    // Consume the press before focused controls see it, then count on release
    // so holding a key cannot trigger the counter repeatedly.
    if (event.type == KeyEventType.KeyUp) {
        model.entry(reader.id, reader.order)?.let(model::count)
    }
    return true
}

/** Same atomic single-file persistence as the Android app. */
class FileDhikrStore(private val file: File) : fi.mazhar.dhikr.DhikrStore {

    override fun load(): fi.mazhar.dhikr.SavedState? = try {
        if (file.exists()) {
            fi.mazhar.dhikr.SavedStateCodec.decode(file.readText(Charsets.UTF_8))
        } else {
            null
        }
    } catch (_: Exception) {
        null
    }

    override fun save(state: fi.mazhar.dhikr.SavedState) {
        Files.createDirectories(file.absoluteFile.parentFile.toPath())
        val tmp = File(file.parentFile, file.name + ".tmp")
        tmp.writeText(fi.mazhar.dhikr.SavedStateCodec.encode(state), Charsets.UTF_8)
        if (!tmp.renameTo(file)) {
            file.writeText(fi.mazhar.dhikr.SavedStateCodec.encode(state), Charsets.UTF_8)
            tmp.delete()
        }
    }
}
